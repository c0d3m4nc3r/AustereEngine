namespace AE
{
    Skybox::Skybox(SPtr<Cubemap> cubemap, SPtr<Mesh> mesh)
        : cubemap(cubemap)
    {
        if (!mesh)
        {
            std::vector<glm::vec3> vertices;
            vertices.reserve(36);

            for (int i = 0; i < 36; i++)
            {
                vertices.push_back(glm::vec3(
                    skyboxVertices[i * 3], 
                    skyboxVertices[i * 3 + 1], 
                    skyboxVertices[i * 3 + 2]
                ));
            }
            
            this->mesh = MakeSPtr<Mesh>(vertices);
        }
    }

    Skybox::~Skybox() {}
}
